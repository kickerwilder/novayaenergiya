"use strict";
/* Маскирование персональных данных (152-ФЗ): перед отправкой текста клиента в LLM и в уведомление менеджеру
   данные заменяются метками:
     [EMAIL], [ТЕЛЕФОН]                     e-mail и телефоны
     [НОМЕР КАРТЫ], [ПАСПОРТ], [НОМЕР]      длинные цифровые номера: карты, паспорт, ИНН, СНИЛС, расчётный счёт
     [АДРЕС]                                адрес: улица с названием и номером дома (кв., корп., стр., подъезд, этаж, офис), «д. 5, кв. 12», индекс рядом со словом «индекс»
     [ФИО]                                  цепочки, похожие на ФИО
   Порядок: e-mail -> номера с явной подписью (паспорт, ИНН, СНИЛС) -> телефоны -> остальные номера -> адреса -> ФИО.
   Работает только с текстом клиента; ответы бота и контакты менеджера не маскируются. Повторный вызов ничего не меняет (метки не содержат цифр,
   улиц и заглавных слов в виде имён). Эвристика намеренно простая: лучше замаскировать лишнее, чем пропустить данные; но цены, мощности,
   ёмкости, габариты, вес, годы, артикулы и коды моделей маскироваться не должны (см. tests/bot_pii.test.js). Тексты и найденные данные нигде не логируются. */

/* ---------- телефоны и e-mail ---------- */
/* телефоны: с кодом страны (+7, 7, 8) и без него, любые разделители (пробел, дефис, точка, скобки); международные номера с «+» */
const PHONE_PATTERNS = [
  /(?<![\d])(?:\+7|7|8)[\s\-.]*\(?\d{3}\)?[\s\-.]*\d{3}[\s\-.]*\d{2}[\s\-.]*\d{2}(?![\d])/g,
  /(?<![\d])\(?[3-9]\d{2}\)?[\s\-.]*\d{3}[\s\-.]*\d{2}[\s\-.]*\d{2}(?![\d])/g,
  /\+\d[\d\s\-().]{8,16}\d/g,
];
const EMAIL = /[A-Za-z0-9._%+\-]+@[A-Za-z0-9\-]+(?:\.[A-Za-z0-9\-]+)+/g;

/* ---------- длинные цифровые номера ---------- */
/* Номера с явной подписью обрабатываются ДО телефонов: десять цифр подряд после слов «паспорт» или «ИНН» это не телефон.
   Без подписи десять цифр подряд, начинающиеся с 3-9, остаются за телефонной функцией (приоритет за ней). */
const PASSPORT_CTX = /(?<![А-Яа-яЁё])(паспорт[а-яё]*[\s:№#.,\-–—]{0,6}(?:(?:серия|серии)[\s:]*)?)(\d{4}[ \-]?\d{6}|\d{2}[ \-]\d{2}[ \-]?\d{6})(?!\d)/gi;
const PASSPORT_SERIES = /(?<![А-Яа-яЁё])(?:серия|серии)[\s:]*\d{4}[\s,;]*(?:номер|№|N)[\s:]*\d{6}(?!\d)/gi;
const INN_CTX = /(?<![А-Яа-яЁё])(ИНН[\s:№#.]{0,4})(\d{12}|\d{10})(?!\d)/gi;
const SNILS_CTX = /(?<![А-Яа-яЁё])(СНИЛС[\s:№#.]{0,4})(\d{3}[ \-]?\d{3}[ \-]?\d{3}[ \-]?\d{2})(?!\d)/gi;

/* Цепочка цифр, разделённых одиночным пробелом или дефисом. Не склеивает числа, между которыми стоят слова или буквы; перед цепочкой не должно быть
   буквы, цифры, «_», «+», «/», «-» или десятичной части (так артикулы z1600-5000-L, ZF16-2002.6 и размеры 45х30х28 в цепочки не попадают). */
const CHAIN = /(?<![\p{L}\p{N}_+\/\-])(?<!\d[.,])\d+(?:[  \-]\d+)*(?![\p{L}\p{N}_])/gu;
const CARD_GROUPS = ["4-4-4-4", "4-4-4-4-3", "4-4-4-1", "4-6-5", "4-6-4"];
const CARD_WORD = /карт[а-яё]*[^\n]{0,25}$/i;

function luhn(digits) {
  let sum = 0;
  for (let i = 0; i < digits.length; i++) {
    let d = Number(digits[digits.length - 1 - i]);
    if (i % 2 === 1) { d *= 2; if (d > 9) d -= 9; }
    sum += d;
  }
  return sum % 10 === 0;
}

/* Что это за цепочка: метка или null. Сплошные цепочки (без пробелов) классифицируются по длине; сгруппированные только по известным
   раскладкам (иначе три числа подряд вроде «1600 4200 2000» или «2800 3800 5000 8600» принимались бы за номера).
   Карту с группами 4-4-4-4 маскируем, если сумма цифр проходит проверку Луна или перед ней стоит слово «карта». */
function classifyChain(chain, before) {
  const groups = chain.split(/[  \-]/);
  const digits = groups.join("");
  const n = digits.length;
  if (n < 10) return null;
  if (groups.length === 1) {
    if (n >= 13 && n <= 19) return "[НОМЕР КАРТЫ]";
    if (n === 10) return "[ПАСПОРТ]";
    return "[НОМЕР]";                       /* 11 (СНИЛС), 12 (ИНН), 20 и больше (счёт) */
  }
  const shape = groups.map((g) => g.length).join("-");
  if (n >= 13 && n <= 19 && CARD_GROUPS.includes(shape)) {
    const named = CARD_WORD.test(before);
    /* перечень «круглых» чисел (мощности и ёмкости: 2800 3800 5000 8600) не карта, даже если сумма случайно проходит проверку Луна */
    if (!named && groups.every((g) => Number(g) > 0 && Number(g) % 100 === 0)) return null;
    return luhn(digits) || named ? "[НОМЕР КАРТЫ]" : null;
  }
  /* паспорт «4512 345678», «45 12 345678»; «круглая» первая четвёрка (1000, 4600, 8600: мощности и ёмкости) с шестизначной ценой паспортом не считается,
     такой паспорт ловится только со словом «паспорт» (PASSPORT_CTX) */
  if (shape === "2-2-6" || (shape === "4-6" && !(Number(groups[0]) > 0 && Number(groups[0]) % 100 === 0))) return "[ПАСПОРТ]";
  if (/^\d{3}-\d{3}-\d{3}[ -]\d{2}$/.test(chain)) return "[НОМЕР]";   /* СНИЛС в обычной записи; «150 300 100 60» без дефисов (перечень мощностей) сюда не относится */
  if (["5-3-1-4-7", "4-4-4-4-4", "5-5-5-5"].includes(shape)) return "[НОМЕР]";   /* расчётный счёт, 20 цифр */
  return null;
}

function maskNumbers(t) {
  t = t.replace(PASSPORT_CTX, "$1[ПАСПОРТ]").replace(PASSPORT_SERIES, "[ПАСПОРТ]");
  t = t.replace(INN_CTX, "$1[НОМЕР]").replace(SNILS_CTX, "$1[НОМЕР]");
  return t;
}

function maskChains(t) {
  return t.replace(CHAIN, (m, offset, str) => classifyChain(m, str.slice(Math.max(0, offset - 40), offset)) || m);
}

/* ---------- адреса ---------- */
const NL = "(?<![\\p{L}\\p{N}_])";            /* перед словом нет буквы или цифры */
const NA = "(?![\\p{L}\\p{N}_])";             /* после слова нет буквы или цифры */
/* маркер улицы: полные слова (в любой форме) и сокращения; «на улице» без названия и номера дома адресом не считается */
const MARKER = new RegExp(
  NL + "(?:улиц[аыеу]|улицей|проспект(?:е|а|у|ом)?|переул(?:ок|ка|ке|ку|ком)|шоссе|бульвар(?:е|а|у|ом)?|набережн(?:ая|ой|ую)|площад(?:ь|и|ью)|микрорайон(?:е|а|у|ом)?)" + NA +
  "|" + NL + "(?:ул|пр-т|пр-кт|просп|пр|пер|ш|б-р|бул|наб|пл|мкр)\\." +
  "|" + NL + "(?:ул|пр-т|пр-кт|б-р)(?=\\s)", "giu");
const STOP_WORDS = new Set(["д", "дом", "кв", "квартира", "корп", "корпус", "к", "стр", "строение", "под", "подъезд", "эт", "этаж", "оф", "офис"]);
const NAME_SMALL = new Set(["лет", "имени", "им", "де", "ван", "дер", "фон"]);
const NAME_TOKEN = /[ \t]*(\d{1,3}(?:-[а-яё]{1,3})?|[А-ЯЁ][а-яё]+(?:-[А-ЯЁа-яё][а-яё]+)*|[а-яё]{2,}(?:-[а-яё]+)*)(?![\p{L}\p{N}_])/uy;
const HOUSE = /[ \t,]*(?:(д|дом)\.?[ \t]*)?(\d{1,4})((?:[А-Яа-я](?![\p{L}\p{N}_]))?(?:\/\d{1,3})?)(?![\p{N}])/iuy;
const SUFFIX = /[,\s]*(?:кв(?:артира)?|корп(?:ус)?|к|стр(?:оение)?|под(?:ъезд)?|эт(?:аж)?|оф(?:ис)?)\.?[ \t]*\d{1,4}(?:[А-Яа-я](?![\p{L}\p{N}_]))?(?:\/\d{1,3})?(?![\p{N}])/iuy;
/* число дома без пометки «д.» не считаем, если дальше стоит единица измерения, цена или время: «на улице Мира 5 градусов» */
const UNIT_WORDS = new Set(["вт", "квт", "кг", "г", "см", "мм", "м", "км", "ч", "час", "часа", "часов", "руб", "р", "рублей", "градусов", "градуса", "шт", "лет", "года", "год", "минут", "мин", "сек", "секунд", "суток", "дней", "день", "дня", "процентов", "метров", "а", "в", "ач"]);
function unitFollows(t, pos) {
  const m = /^[ \t]*([А-Яа-яЁёA-Za-z]+|%|₽|°)/.exec(t.slice(pos, pos + 20));
  return !!m && (m[1] === "%" || m[1] === "₽" || m[1] === "°" || UNIT_WORDS.has(m[1].toLowerCase()));
}

/* От маркера улицы: название (1-4 слова), номер дома, затем кв./корп./стр./подъезд/этаж/офис. Возвращает конец адреса или -1. */
function parseStreetAddress(t, markerEnd, abbrDot) {
  let p = markerEnd, tokens = 0, caps = 0, lower = 0;
  while (tokens < 4) {
    NAME_TOKEN.lastIndex = p;
    const m = NAME_TOKEN.exec(t);
    if (!m) break;
    const w = m[1], lw = w.toLowerCase();
    if (STOP_WORDS.has(lw)) break;
    if (/^\d/.test(w)) { if (tokens > 0) break; }           /* число только в начале названия: «8 Марта», «1-я Парковая» */
    else if (/^[А-ЯЁ]/.test(w)) caps++;
    else if (caps > 0) { if (!NAME_SMALL.has(lw)) break; }  /* после названия с заглавной допустимы только «лет», «имени»… */
    else lower++;
    tokens++; p = NAME_TOKEN.lastIndex;
  }
  if (tokens === 0 || (tokens === 1 && /^\d/.test(t.slice(markerEnd).trim()))) return -1;
  HOUSE.lastIndex = p;
  const h = HOUSE.exec(t);
  if (!h) return -1;
  const marked = !!h[1];
  if (!marked) {
    if (!(caps > 0 || (abbrDot && lower > 0))) return -1;   /* строчное название и полное слово «улица» требуют пометки «д.» или «дом» */
    if (unitFollows(t, HOUSE.lastIndex)) return -1;
  } else if (caps === 0 && lower === 0) return -1;
  p = HOUSE.lastIndex;
  for (;;) {
    SUFFIX.lastIndex = p;
    const s = SUFFIX.exec(t);
    if (!s) break;
    p = SUFFIX.lastIndex;
  }
  return p;
}

function maskStreets(t) {
  let out = "", i = 0, m;
  MARKER.lastIndex = 0;
  while ((m = MARKER.exec(t))) {
    const end = parseStreetAddress(t, m.index + m[0].length, /\.$/.test(m[0]) || /^(?:ул|пр-т|пр-кт|б-р)$/i.test(m[0]));
    if (end > 0) { out += t.slice(i, m.index) + "[АДРЕС]"; i = end; MARKER.lastIndex = end; }
  }
  return out + t.slice(i);
}

/* «д. 5, кв. 12» и «кв. 12» без улицы; индекс только рядом со словом «индекс» */
const HOUSE_FLAT = /(?<![\p{L}\p{N}_])(?:д\.|дом)[ \t]*\d{1,4}(?:[А-Яа-я](?![\p{L}\p{N}_]))?(?:\/\d{1,3})?(?:[,\s]*(?:корп(?:ус)?|к|стр(?:оение)?)\.?[ \t]*\d{1,3})*[,\s]*кв(?:артира)?\.?[ \t]*\d{1,4}(?:[А-Яа-я](?![\p{L}\p{N}_]))?/giu;
const FLAT_ONLY = /(?<![\p{L}\p{N}_])кв\.[ \t]*\d{1,4}(?![\p{N}])/giu;
const INDEX_AFTER_WORD = /((?<![\p{L}])индекс[а-яё]*[\s:.,№#\-]{0,4})(\d{6})(?!\d)/giu;
const INDEX_BEFORE_WORD = /(?<![\d])(\d{6})(?=[\s,(]{0,3}индекс(?![\p{L}]))/giu;

function maskAddresses(t) {
  t = maskStreets(t);
  t = t.replace(HOUSE_FLAT, "[АДРЕС]").replace(FLAT_ONLY, "[АДРЕС]");
  return t.replace(INDEX_AFTER_WORD, "$1[АДРЕС]").replace(INDEX_BEFORE_WORD, "[АДРЕС]");
}

/* ---------- ФИО ---------- */
/* ФИО: 2–3 слова с заглавной буквы подряд, среди которых есть отчество или фамилия (по окончанию); слова предметной области не считаются */
const WORD = "[А-ЯЁ][а-яё]{2,}";
const NAME_CHAIN = new RegExp("(?<![А-Яа-яЁё])" + WORD + "(?:[ \\t]+" + WORD + "){1,2}(?![А-Яа-яЁё])", "g");
const PATRONYMIC = /(?:ович|евич|ьич|овна|евна|ична|инична|ыч)$/;
const SURNAME = /(?:ов|ова|ев|ева|ёв|ёва|ин|ина|ын|ына|ский|ская|цкий|цкая|ской|енко|ко|юк|чук|ук|ик|ян|дзе)$/;
const NOT_NAMES = new Set(["Станция", "Станции", "Станцию", "Станцией", "Новая", "Энергия", "Энерджи", "Внешний", "Аккумулятор",
  "Зарядная", "Портативная", "Тёмный", "Темный", "Светлый", "Корпус", "Крым", "Москва", "Россия", "Симферополь", "Севастополь", "Дача", "Дом"]);
/* инициалы: «Иванов И.И.», «И.И. Иванов» */
const INITIALS_AFTER = /(?<![А-Яа-яЁё])[А-ЯЁ][а-яё]{2,}[ \t]+[А-ЯЁ]\.[ \t]*[А-ЯЁ]\.?/g;
const INITIALS_BEFORE = /(?<![А-Яа-яЁё])[А-ЯЁ]\.[ \t]*[А-ЯЁ]\.[ \t]*[А-ЯЁ][а-яё]{2,}/g;

function looksLikeName(chain) {
  const words = chain.split(/[ \t]+/);
  if (words.some((w) => NOT_NAMES.has(w))) return false;
  if (words.some((w) => w.length >= 6 && PATRONYMIC.test(w))) return true;
  return words.length >= 2 && words.some((w) => w.length >= 4 && SURNAME.test(w));
}

function maskPII(text) {
  let t = String(text == null ? "" : text);
  t = t.replace(EMAIL, "[EMAIL]");
  t = maskNumbers(t);                                   /* номера с подписью «паспорт», «ИНН», «СНИЛС» */
  for (const re of PHONE_PATTERNS) t = t.replace(re, "[ТЕЛЕФОН]");
  t = maskChains(t);                                    /* карты, паспорт, ИНН, СНИЛС, счёт без подписи */
  t = maskAddresses(t);
  t = t.replace(INITIALS_AFTER, "[ФИО]").replace(INITIALS_BEFORE, "[ФИО]");
  t = t.replace(NAME_CHAIN, (m) => (looksLikeName(m) ? "[ФИО]" : m));
  return t;
}

module.exports = { maskPII };
