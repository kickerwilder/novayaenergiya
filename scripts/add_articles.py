def main():
    assert len(ARTICLES) == 42 and sum(k.endswith("-D") for k in ARTICLES) == 22 and sum(k.endswith("-L") for k in ARTICLES) == 20
    data = catalog_io.load()
    codes = {v["code"]: v for c in data["combos"] for v in c["vers"].values()}
    missing = sorted(set(ARTICLES) - set(codes))
    extra = sorted(set(codes) - set(ARTICLES))
    if missing or extra:
        print("СВЕРКА НЕ СОШЛАСЬ, файл не изменён.")
        if missing:
            print("  коды из таблицы, которых нет в каталоге:", ", ".join(missing))
        if extra:
            print("  версии каталога, которых нет в таблице:", ", ".join(extra))
        sys.exit(1)

    for c in data["combos"]:
        for k, v in list(c["vers"].items()):
            art = ARTICLES[v["code"]]
            if "article" in v:
                v["article"] = art
            else:  # поле ставим сразу после code, остальные поля не трогаем
                c["vers"][k] = {kk: vv for kk, vv in _with_article(v, art)}
    changed = catalog_io.save(data)
    print("Артикулы: %d из %d версий; %s" % (len(codes), len(codes), "каталог обновлён" if changed else "без изменений"))


def _with_article(v, art):
    for kk, vv in v.items():
        yield kk, vv
        if kk == "code":
            yield "article", art


if __name__ == "__main__":
    main()
